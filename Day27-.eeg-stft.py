import mne
import numpy as np
import matplotlib.pyplot as plt
from scipy.signal import spectrogram
import warnings
warnings.filterwarnings("ignore")

# 2. 加载数据 (使用受试者1，runs=[4]运动想象数据)
print("Loading EEG data...")
data_path = mne.datasets.eegbci.load_data(subjects=[1], runs=[4])[0]
raw = mne.io.read_raw_edf(data_path, preload=True, verbose=False)

# 【核心修复】动态匹配 C3 通道
c3_name = [ch for ch in raw.ch_names if 'C3' in ch][0]
print(f"找到的 C3 通道名是: {c3_name}")

raw.pick([c3_name]) # 只保留该通道
raw.filter(l_freq=1.0, h_freq=40.0, verbose=False)

# 提取 10 秒数据
data = raw.get_data()[0] * 1e6
fs = raw.info['sfreq']
times = np.arange(len(data)) / fs

# 3. 核心计算：短时傅里叶变换 (STFT)
print("Computing Spectrogram...")
f, t, Sxx = spectrogram(data, fs, nperseg=int(fs*1), noverlap=int(fs*0.5))

# 转换为分贝 (dB)，方便画图
Sxx_db = 10 * np.log10(Sxx + 1e-10)

# 4. 画图（时频图）
# 截取前 10 秒的数据来画图
t_start = int(0 * fs)
t_end = int(10 * fs)
data_segment = data[t_start:t_end]
times_segment = np.arange(len(data_segment)) / fs

# 重新计算 STFT (只看这 10 秒)
f, t, Sxx = spectrogram(data_segment, fs, nperseg=int(fs*1), noverlap=int(fs*0.5))
Sxx_db = 10 * np.log10(Sxx + 1e-10)

plt.figure(figsize=(12, 6))
# 使用 vmin 和 vmax 强行拉伸对比度，让微弱的变化显现出来
plt.pcolormesh(t, f, Sxx_db, shading='gouraud', cmap='jet', vmin=-40, vmax=10)
plt.title(f"Time-Frequency Representation (10s window) - Channel {c3_name}")
plt.xlabel("Time (s)")
plt.ylabel("Frequency (Hz)")
plt.ylim(8, 30) # 👈 核心：只看 8-30Hz！
plt.colorbar(label="Power/Frequency (dB/Hz)")
plt.grid(False)
plt.show()