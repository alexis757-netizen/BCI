# 2. 加载数据
print("Loading EEG data...")
data_path = mne.datasets.eegbci.load_data(subjects=[1], runs=[3])[0]
raw = mne.io.read_raw_edf(data_path, preload=True, verbose=False)

# 👇 【核心修复】调用官方函数，把通道名标准化（比如把 Fc5. 变成 Fc5）
mne.datasets.eegbci.standardize(raw)

# 滤波与重参考
raw.filter(l_freq=1.0, h_freq=40.0, verbose=False)
raw.set_eeg_reference('average', projection=False, verbose=False)

# 👇 赋予标准 10-20 电极位置
montage = mne.channels.make_standard_montage('standard_1020')
raw.set_montage(montage, on_missing='ignore')

# 截取前 30 秒
raw.crop(tmin=0, tmax=30)

# 3. 构建 ICA 模型
print("Fitting ICA (this may take a few seconds)...")
ica = ICA(n_components=15, random_state=97, max_iter="auto")
ica.fit(raw)

# 4. 画出地形图
ica.plot_components(picks=range(15), ch_type='eeg')
plt.show()

