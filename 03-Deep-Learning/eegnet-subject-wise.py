import mne
import numpy as np
import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import DataLoader, TensorDataset
import matplotlib.pyplot as plt
import scipy.linalg
import warnings
warnings.filterwarnings("ignore")

# ================= 2. 定义 EA 算法 =================
def euclidean_alignment(X):
    covs = np.array([np.cov(x) for x in X])
    mean_cov = np.mean(covs, axis=0)
    R_inv_sqrt = np.linalg.inv(scipy.linalg.sqrtm(mean_cov))
    if np.iscomplexobj(R_inv_sqrt):
        R_inv_sqrt = R_inv_sqrt.real
    X_aligned = np.array([R_inv_sqrt @ x for x in X])
    return X_aligned

# ================= 3. 加载并分离数据 =================
print("Downloading and processing data (Subject-wise Split)...")
# 我们用 1,2,3,4 训练，用 5 测试
train_subjects = [1, 2, 3, 4]
test_subject = 5

def process_subject(sub):
    data_path = mne.datasets.eegbci.load_data(subjects=[sub], runs=[4])[0]
    raw = mne.io.read_raw_edf(data_path, preload=True, verbose=False)
    raw.filter(l_freq=8.0, h_freq=30.0, verbose=False)
    events, event_id = mne.events_from_annotations(raw, verbose=False)
    event_id_binary = {'T1': event_id['T1'], 'T2': event_id['T2']}
    fs = raw.info['sfreq']
    data_all = raw.get_data() * 1e6

    window_size = int(1.0 * fs)
    step_size = int(0.2 * fs)

    X_sub_aug = []
    y_sub_aug = []

    for event in events:
        if event[2] not in [event_id_binary['T1'], event_id_binary['T2']]:
            continue
        label = 0 if event[2] == event_id_binary['T1'] else 1
        start_idx = event[0] + int(0.5 * fs)
        end_idx = event[0] + int(3.5 * fs)
        for i in range(start_idx, end_idx - window_size, step_size):
            X_sub_aug.append(data_all[:, i : i + window_size])
            y_sub_aug.append(label)

    X_sub_aligned = euclidean_alignment(np.array(X_sub_aug))
    return X_sub_aligned, np.array(y_sub_aug)

X_train_list, y_train_list = [], []
for sub in train_subjects:
    print(f"Loading train subject {sub}...")
    X_s, y_s = process_subject(sub)
    X_train_list.append(X_s)
    y_train_list.append(y_s)

print(f"Loading test subject {test_subject}...")
X_test_raw, y_test = process_subject(test_subject)

# 拼接训练集
X_train_raw = np.concatenate(X_train_list, axis=0)
y_train = np.concatenate(y_train_list, axis=0)

# 增加通道维度
X_train_raw = np.expand_dims(X_train_raw, axis=1)
X_test_raw = np.expand_dims(X_test_raw, axis=1)

# ================= 4. 严谨的标准化（防止测试集泄露） =================
# 计算训练集的均值和标准差
train_mean = X_train_raw.mean()
train_std = X_train_raw.std()

X_train = (X_train_raw - train_mean) / train_std
X_test = (X_test_raw - train_mean) / train_std  # 用训练集的参数来标准化测试集

# 转为 Tensor
X_train = torch.tensor(X_train, dtype=torch.float32)
y_train = torch.tensor(y_train, dtype=torch.long)
X_test = torch.tensor(X_test, dtype=torch.float32)
y_test = torch.tensor(y_test, dtype=torch.long)

train_dataset = TensorDataset(X_train, y_train)
train_loader = DataLoader(train_dataset, batch_size=32, shuffle=True)

# ================= 5. 定义 EEGNet =================
class EEGNet(nn.Module):
    def __init__(self, n_channels, n_classes=2):
        super(EEGNet, self).__init__()
        self.conv1 = nn.Conv2d(1, 8, kernel_size=(1, 64), padding='same', bias=False)
        self.batchnorm1 = nn.BatchNorm2d(8)
        self.depthwise = nn.Conv2d(8, 16, kernel_size=(n_channels, 1), groups=8, bias=False)
        self.batchnorm2 = nn.BatchNorm2d(16)
        self.dropout1 = nn.Dropout(0.5) # 加大 Dropout 防止过拟合
        self.adaptive_pool = nn.AdaptiveAvgPool2d((1, 1))
        self.fc = nn.Linear(16, n_classes)

    def forward(self, x):
        x = self.conv1(x)
        x = self.batchnorm1(x)
        x = self.depthwise(x)
        x = self.batchnorm2(x)
        x = self.adaptive_pool(x)
        x = self.dropout1(x)
        x = x.view(x.size(0), -1)
        x = self.fc(x)
        return x

model = EEGNet(n_channels=X_train.shape[2])
criterion = nn.CrossEntropyLoss()
optimizer = optim.Adam(model.parameters(), lr=0.001, weight_decay=1e-4) # 加入权重衰减

# ================= 6. 训练 =================
print("\nStarting EEGNet Training (Subject-wise)...")
epochs_num = 30
loss_history = []

for epoch in range(epochs_num):
    model.train()
    running_loss = 0.0
    for inputs, labels in train_loader:
        optimizer.zero_grad()
        outputs = model(inputs)
        loss = criterion(outputs, labels)
        loss.backward()
        optimizer.step()
        running_loss += loss.item()

    avg_loss = running_loss / len(train_loader)
    loss_history.append(avg_loss)
    if (epoch + 1) % 5 == 0:
        print(f"Epoch [{epoch+1}/{epochs_num}], Loss: {avg_loss:.4f}")

# ================= 7. 盲测 Subject 5 =================
model.eval()
with torch.no_grad():
    test_outputs = model(X_test)
    _, predicted = torch.max(test_outputs.data, 1)
    correct = (predicted == y_test).sum().item()
    accuracy = correct / len(y_test)
    print(f"\n[TEST ON UNSEEN SUBJECT 5] Accuracy: {accuracy * 100:.2f}%")

plt.plot(loss_history, color='orange', linewidth=2)
plt.title("EEGNet Training Loss (Train on 1,2,3,4 -> Test on 5)")
plt.xlabel("Epoch")
plt.ylabel("Loss")
plt.grid(True)
plt.show()