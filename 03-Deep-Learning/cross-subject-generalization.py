import mne
import numpy as np
import matplotlib.pyplot as plt
from mne.decoding import CSP
from sklearn.svm import SVC
from sklearn.pipeline import Pipeline
from sklearn.metrics import accuracy_score, ConfusionMatrixDisplay
import warnings
warnings.filterwarnings("ignore")

# ================= 2. 定义数据加载与切片函数 =================
def get_subject_data(subject_id):
    print(f"Loading data for Subject {subject_id}...")
    data_path = mne.datasets.eegbci.load_data(subjects=[subject_id], runs=[4])[0]
    raw = mne.io.read_raw_edf(data_path, preload=True, verbose=False)
    raw.filter(l_freq=8.0, h_freq=30.0, verbose=False)

    events, event_id = mne.events_from_annotations(raw, verbose=False)
    event_id_binary = {'T1': event_id['T1'], 'T2': event_id['T2']}
    fs = raw.info['sfreq']
    data_all = raw.get_data() * 1e6

    X_aug, y_aug = [], []
    window_size = int(1.0 * fs)
    step_size = int(0.2 * fs)

    for event in events:
        if event[2] not in [event_id_binary['T1'], event_id_binary['T2']]:
            continue
        label = event[2]
        start_idx = event[0] + int(0.5 * fs)
        end_idx = event[0] + int(3.5 * fs)

        for i in range(start_idx, end_idx - window_size, step_size):
            X_aug.append(data_all[:, i : i + window_size])
            y_aug.append(label)

    return np.array(X_aug), np.array(y_aug)

# ================= 3. 加载数据 =================
X_train, y_train = get_subject_data(subject_id=1) # 张三的数据（训练）
X_test, y_test = get_subject_data(subject_id=2)   # 李四的数据（盲测）

print(f"\n张三维度: {X_train.shape}, 李四维度: {X_test.shape}")

# ================= 4. 训练与跨受试者预测 =================
print("\nTraining on Subject 1 (Zhang San)...")
csp = CSP(n_components=4, reg=None, log=True, norm_trace=False)
svm = SVC(kernel='linear')
clf = Pipeline([('CSP', csp), ('SVM', svm)])

# 只用张三的数据来 fit（训练）
clf.fit(X_train, y_train)

# 直接拿模型去预测李四的数据！
print("Testing on Subject 2 (Li Si)...")
y_pred = clf.predict(X_test)

accuracy = accuracy_score(y_test, y_pred)
print(f"\nCross-Subject Accuracy: {accuracy * 100:.2f}%")

# 5. 画图
plt.figure(figsize=(6, 5))
ConfusionMatrixDisplay.from_predictions(
    y_test, y_pred,
    display_labels=['Left Hand', 'Right Hand'],
    cmap=plt.cm.Reds # 用红色，代表“翻车”
)
plt.title("Cross-Subject Prediction (Subject 1 -> Subject 2)")
plt.show()