import mne
import numpy as np
import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import DataLoader, TensorDataset
import matplotlib.pyplot as plt
import scipy.linalg
import warnings
warnings.filterwarnings("ignore")

# ================= 2. 定义 EA 算法 =================
def euclidean_alignment(X):
    covs = np.array([np.cov(x) for x in X])
    mean_cov = np.mean(covs, axis=0)
    R_inv_sqrt = np.linalg.inv(scipy.linalg.sqrtm(mean_cov))
    if np.iscomplexobj(R_inv_sqrt):
        R_inv_sqrt = R_inv_sqrt.real
    X_aligned = np.array([R_inv_sqrt @ x for x in X])
    return X_aligned

# ================= 3. 数据加载 =================
def process_subject(sub):
    data_path = mne.datasets.eegbci.load_data(subjects=[sub], runs=[4])[0]
    raw = mne.io.read_raw_edf(data_path, preload=True, verbose=False)
    raw.filter(l_freq=8.0, h_freq=30.0, verbose=False)
    events, event_id = mne.events_from_annotations(raw, verbose=False)
    event_id_binary = {'T1': event_id['T1'], 'T2': event_id['T2']}
    fs = raw.info['sfreq']
    data_all = raw.get_data() * 1e6

    window_size = int(1.0 * fs)
    step_size = int(0.2 * fs)
    X_sub_aug, y_sub_aug = [], []

    for event in events:
        if event[2] not in [event_id_binary['T1'], event_id_binary['T2']]: continue
        label = 0 if event[2] == event_id_binary['T1'] else 1
        start_idx = event[0] + int(0.5 * fs)
        end_idx = event[0] + int(3.5 * fs)
        for i in range(start_idx, end_idx - window_size, step_size):
            X_sub_aug.append(data_all[:, i : i + window_size])
            y_sub_aug.append(label)

    return euclidean_alignment(np.array(X_sub_aug)), np.array(y_sub_aug)

print("Loading Data...")
X_train_list, y_train_list = [], []
for sub in [1, 2, 3, 4]:
    X_s, y_s = process_subject(sub)
    X_train_list.append(X_s)
    y_train_list.append(y_s)

X_test_raw, y_test = process_subject(5)

X_train_raw = np.concatenate(X_train_list, axis=0)
y_train = np.concatenate(y_train_list, axis=0)
X_train_raw = np.expand_dims(X_train_raw, axis=1)
X_test_raw = np.expand_dims(X_test_raw, axis=1)

# 标准化
train_mean, train_std = X_train_raw.mean(), X_train_raw.std()
X_train = torch.tensor((X_train_raw - train_mean) / train_std, dtype=torch.float32)
y_train = torch.tensor(y_train, dtype=torch.long)
X_test = torch.tensor((X_test_raw - train_mean) / train_std, dtype=torch.float32)
y_test = torch.tensor(y_test, dtype=torch.long)

# ================= 4. 定义 EEGNet =================
class EEGNet(nn.Module):
    def __init__(self, n_channels, n_classes=2):
        super(EEGNet, self).__init__()
        self.conv1 = nn.Conv2d(1, 8, kernel_size=(1, 64), padding='same', bias=False)
        self.batchnorm1 = nn.BatchNorm2d(8)
        self.depthwise = nn.Conv2d(8, 16, kernel_size=(n_channels, 1), groups=8, bias=False)
        self.batchnorm2 = nn.BatchNorm2d(16)
        self.dropout1 = nn.Dropout(0.5)
        self.adaptive_pool = nn.AdaptiveAvgPool2d((1, 1))
        self.fc = nn.Linear(16, n_classes)

    def forward(self, x):
        x = self.conv1(x)
        x = self.batchnorm1(x)
        x = self.depthwise(x)
        x = self.batchnorm2(x)
        x = self.adaptive_pool(x)
        x = self.dropout1(x)
        x = x.view(x.size(0), -1)
        x = self.fc(x)
        return x

model = EEGNet(n_channels=X_train.shape[2])
criterion = nn.CrossEntropyLoss()

# ================= 5. 第一步：基础训练 (Base Training) =================
print("\nStep 1: Training Base Model on Subjects 1-4...")
optimizer = optim.Adam(model.parameters(), lr=0.001, weight_decay=1e-4)
train_loader = DataLoader(TensorDataset(X_train, y_train), batch_size=32, shuffle=True)

for epoch in range(15): # 为了省时间，基础训练跑 15 轮
    model.train()
    for inputs, labels in train_loader:
        optimizer.zero_grad()
        loss = criterion(model(inputs), labels)
        loss.backward()
        optimizer.step()

# 评估微调前的模型
model.eval()
with torch.no_grad():
    base_pred = model(X_test)
    base_acc = (base_pred.argmax(1) == y_test).sum().item() / len(y_test)
print(f"Accuracy on Subject 5 BEFORE Fine-tuning: {base_acc * 100:.2f}%")

# ================= 6. 第二步：个体微调 (Fine-tuning) =================
print("\nStep 2: Fine-tuning with 20% of Subject 5's data...")

# 将受试者 5 的数据拆分为 20% 校准集，80% 测试集
cal_size = int(0.2 * len(X_test))
X_calib, y_calib = X_test[:cal_size], y_test[:cal_size]
X_final_test, y_final_test = X_test[cal_size:], y_test[cal_size:]

# 【核心】冻结特征提取层，只放开全连接层 (fc) 进行微调
for param in model.parameters():
    param.requires_grad = False # 把所有的冻结掉
for param in model.fc.parameters():
    param.requires_grad = True  # 只打开最后一层

# 使用极小的学习率 (1e-4) 进行微调
optimizer_ft = optim.Adam(filter(lambda p: p.requires_grad, model.parameters()), lr=0.0001)
calib_loader = DataLoader(TensorDataset(X_calib, y_calib), batch_size=8, shuffle=True)

model.train()
for epoch in range(20): # 在 20% 的小数据上狂练 20 轮
    for inputs, labels in calib_loader:
        optimizer_ft.zero_grad()
        loss = criterion(model(inputs), labels)
        loss.backward()
        optimizer_ft.step()

# ================= 7. 最终评估 =================
model.eval()
with torch.no_grad():
    ft_pred = model(X_final_test)
    ft_acc = (ft_pred.argmax(1) == y_final_test).sum().item() / len(y_final_test)
print(f"Accuracy on Subject 5 AFTER Fine-tuning (on unseen 80%): {ft_acc * 100:.2f}%")

# 画对比图
plt.bar(['Before FT', 'After FT'], [base_acc * 100, ft_acc * 100], color=['gray', 'green'], edgecolor='black')
plt.ylabel("Accuracy (%)")
plt.title("Subject 5 Accuracy: Before vs After Fine-tuning")
plt.ylim(0, 100)
plt.show()