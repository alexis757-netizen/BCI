import mne
import numpy as np
import matplotlib.pyplot as plt
from scipy.signal import spectrogram
import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import DataLoader, TensorDataset
import warnings
warnings.filterwarnings("ignore")

# ================= 2. 数据加载与 STFT 转化 =================
print("Loading and Converting EEG to Spectrograms...")
data_path = mne.datasets.eegbci.load_data(subjects=[1], runs=[4])[0]
raw = mne.io.read_raw_edf(data_path, preload=True, verbose=False)
raw.filter(l_freq=8.0, h_freq=30.0, verbose=False)

events, event_id = mne.events_from_annotations(raw, verbose=False)
event_id_binary = {'T1': event_id['T1'], 'T2': event_id['T2']}
fs = raw.info['sfreq']
data_all = raw.get_data() * 1e6

X_img, y_img = [], []
window_size = int(1.0 * fs)
step_size = int(0.2 * fs)

for event in events:
    if event[2] not in [event_id_binary['T1'], event_id_binary['T2']]: continue
    label = 0 if event[2] == event_id_binary['T1'] else 1
    start_idx = event[0] + int(0.5 * fs)
    end_idx = event[0] + int(3.5 * fs)

    for i in range(start_idx, end_idx - window_size, step_size):
        window_data = data_all[:, i : i + window_size] # (64, 160)

        # 我们只挑 C3 和 C4 两个核心通道来做时频图
        c3_idx = raw.ch_names.index([ch for ch in raw.ch_names if 'C3' in ch][0])
        c4_idx = raw.ch_names.index([ch for ch in raw.ch_names if 'C4' in ch][0])

        # 计算 STFT (只看 8-30Hz)
        f, t, Sxx_c3 = spectrogram(window_data[c3_idx], fs, nperseg=int(fs*0.5), noverlap=int(fs*0.25))
        _, _, Sxx_c4 = spectrogram(window_data[c4_idx], fs, nperseg=int(fs*0.5), noverlap=int(fs*0.25))

        # 只取 8-30Hz 对应的频率索引
        freq_mask = (f >= 8) & (f <= 30)
        Sxx_c3 = Sxx_c3[freq_mask]
        Sxx_c4 = Sxx_c4[freq_mask]

        # 把 C3 和 C4 拼成一张 2 通道的“图片” (类似 RGB 图片的 R 和 G 通道)
        img = np.stack([Sxx_c3, Sxx_c4], axis=0)
        img = (img - np.mean(img)) / (np.std(img) + 1e-8) # 标准化

        X_img.append(img)
        y_img.append(label)

X = np.array(X_img)
y = np.array(y_img)
print(f"STFT 图片数据集维度: {X.shape}") # (样本数, 2, 频率数, 时间点)

# 转为 Tensor
X = torch.tensor(X, dtype=torch.float32)
y = torch.tensor(y, dtype=torch.long)

train_size = int(0.8 * len(X))
X_train, X_test = X[:train_size], X[train_size:]
y_train, y_test = y[:train_size], y[train_size:]

train_loader = DataLoader(TensorDataset(X_train, y_train), batch_size=16, shuffle=True)

# ================= 3. 定义 2D 图像卷积网络 =================
class ImageEEGNet(nn.Module):
    def __init__(self):
        super(ImageEEGNet, self).__init__()
        # 这里用的是 2D 卷积，专门处理图片 (输入通道是 2：C3和C4)
        self.conv1 = nn.Conv2d(2, 16, kernel_size=3, padding=1)
        self.relu = nn.ReLU()
        self.pool = nn.MaxPool2d(2, 2)
        self.dropout = nn.Dropout(0.5)

        # 自适应池化，不管输入图片多大，都压成 1x1
        self.adaptive_pool = nn.AdaptiveAvgPool2d((1, 1))
        self.fc = nn.Linear(16, 2)

    def forward(self, x):
        x = self.conv1(x)
        x = self.relu(x)
        x = self.pool(x)
        x = self.adaptive_pool(x)
        x = self.dropout(x)
        x = x.view(x.size(0), -1)
        x = self.fc(x)
        return x

model = ImageEEGNet()
criterion = nn.CrossEntropyLoss()
optimizer = optim.Adam(model.parameters(), lr=0.001)

# ================= 4. 训练 =================
print("\nTraining 2D CNN on Spectrograms...")
epochs = 20
for epoch in range(epochs):
    model.train()
    for inputs, labels in train_loader:
        optimizer.zero_grad()
        outputs = model(inputs)
        loss = criterion(outputs, labels)
        loss.backward()
        optimizer.step()

# ================= 5. 评估 =================
model.eval()
with torch.no_grad():
    test_outputs = model(X_test)
    acc = (test_outputs.argmax(1) == y_test).sum().item() / len(y_test)
    print(f"\n2D CNN Accuracy: {acc * 100:.2f}%")