import mne
import numpy as np
import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import DataLoader, TensorDataset
import matplotlib.pyplot as plt
import warnings
warnings.filterwarnings("ignore")

# ================= 2. 加载数据并使用滑动窗口增强 =================
print("Loading and Augmenting EEG data...")
data_path = mne.datasets.eegbci.load_data(subjects=[1], runs=[4])[0]
raw = mne.io.read_raw_edf(data_path, preload=True, verbose=False)
raw.filter(l_freq=8.0, h_freq=30.0, verbose=False)

events, event_id = mne.events_from_annotations(raw, verbose=False)
event_id_binary = {'T1': event_id['T1'], 'T2': event_id['T2']}
fs = raw.info['sfreq']
data_all = raw.get_data() * 1e6

X_aug, y_aug = [], []
window_size = int(1.0 * fs)  # 1秒窗口
step_size = int(0.2 * fs)    # 0.2秒步长

for event in events:
    if event[2] not in [event_id_binary['T1'], event_id_binary['T2']]:
        continue
    label = 0 if event[2] == event_id_binary['T1'] else 1

    start_idx = event[0] + int(0.5 * fs)
    end_idx = event[0] + int(3.5 * fs)

    for i in range(start_idx, end_idx - window_size, step_size):
        X_aug.append(data_all[:, i : i + window_size])
        y_aug.append(label)

X = np.expand_dims(np.array(X_aug), axis=1) # 加上通道维度 (样本, 1, 64, 160)
y = torch.tensor(y_aug, dtype=torch.long)
X = torch.tensor(X, dtype=torch.float32)

print(f"数据增强后维度: {X.shape}, 标签维度: {y.shape}")

# 引入打乱函数
import random
indices = list(range(len(X)))
random.seed(42)
random.shuffle(indices)

X = X[indices]
y = y[indices]
# 对数据进行标准化处理
X = (X - X.mean()) / X.std()
# 然后再切分 80% 和 20%
train_size = int(0.8 * len(X))
X_train, X_test = X[:train_size], X[train_size:]
y_train, y_test = y[:train_size], y[train_size:]

train_dataset = TensorDataset(X_train, y_train)
train_loader = DataLoader(train_dataset, batch_size=16, shuffle=True) # batch_size调大

# ================= 3. 定义 EEGNet 网络结构 =================
class EEGNet(nn.Module):
    def __init__(self, n_channels, n_classes=2):
        super(EEGNet, self).__init__()
        self.conv1 = nn.Conv2d(1, 8, kernel_size=(1, 64), padding='same', bias=False)
        self.batchnorm1 = nn.BatchNorm2d(8)
        self.depthwise = nn.Conv2d(8, 16, kernel_size=(n_channels, 1), groups=8, bias=False)
        self.batchnorm2 = nn.BatchNorm2d(16)
        self.dropout1 = nn.Dropout(0.25)
        self.adaptive_pool = nn.AdaptiveAvgPool2d((1, 1))
        self.fc = nn.Linear(16, n_classes)

    def forward(self, x):
        x = self.conv1(x)
        x = self.batchnorm1(x)
        x = self.depthwise(x)
        x = self.batchnorm2(x)
        x = self.adaptive_pool(x)
        x = self.dropout1(x)
        x = x.view(x.size(0), -1)
        x = self.fc(x)
        return x

model = EEGNet(n_channels=X.shape[2])
criterion = nn.CrossEntropyLoss()
optimizer = optim.Adam(model.parameters(), lr=0.001)

# ================= 4. 开始训练模型 =================
print("\nStarting EEGNet Training (30 Epochs on Augmented Data)...")
epochs_num = 50
loss_history = []

for epoch in range(epochs_num):
    model.train()
    running_loss = 0.0
    for inputs, labels in train_loader:
        optimizer.zero_grad()
        outputs = model(inputs)
        loss = criterion(outputs, labels)
        loss.backward()
        optimizer.step()
        running_loss += loss.item()

    avg_loss = running_loss / len(train_loader)
    loss_history.append(avg_loss)
    if (epoch + 1) % 5 == 0:
        print(f"Epoch [{epoch+1}/{epochs_num}], Loss: {avg_loss:.4f}")

# ================= 5. 评估与画图 =================
model.eval()
with torch.no_grad():
    test_outputs = model(X_test)
    _, predicted = torch.max(test_outputs.data, 1)
    correct = (predicted == y_test).sum().item()
    accuracy = correct / len(y_test)
    print(f"\nEEGNet Test Accuracy on Augmented Data: {accuracy * 100:.2f}%")

plt.plot(loss_history, color='red')
plt.title("EEGNet Training Loss (Augmented Data)")
plt.xlabel("Epoch")
plt.ylabel("Loss")
plt.show()